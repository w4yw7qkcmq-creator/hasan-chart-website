function normalizeReasonCode(raw) {
  if (!raw) return null;
  const key = String(raw).trim();
  if (REASON_CODES[key]) return REASON_CODES[key];
  if (LEGACY_REASON_MAP[key]) return LEGACY_REASON_MAP[key];
  return key;
}

function mapBlockedToOutcome(reasonCode) {
  if (reasonCode === REASON_CODES.SOURCE_QUARANTINED) return DECISION_OUTCOMES.QUARANTINED;
  if (reasonCode === REASON_CODES.PARSER_CONFIDENCE_LOW) return DECISION_OUTCOMES.DEGRADED;
  return DECISION_OUTCOMES.BLOCKED;
}

