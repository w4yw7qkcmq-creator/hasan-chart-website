const { REASON_CODES } = require("./reason-taxonomy");

const FAILURE_ATTRIBUTION = Object.freeze({
  SOURCE_CAUSED: "SOURCE_CAUSED",
  PIPELINE_CAUSED: "PIPELINE_CAUSED",
  NETWORK_CAUSED: "NETWORK_CAUSED",
  EXPECTED_NO_DATA: "EXPECTED_NO_DATA",
});

const PIPELINE_REASON_CODES = new Set([
  REASON_CODES.DUPLICATE_BLOCKED,
  REASON_CODES.QUALITY_GATE_BLOCKED,
  REASON_CODES.HALLUCINATED_NUMERIC_TOKEN,
  REASON_CODES.EDITORIAL_OUTPUT_INVALID,
  REASON_CODES.FAMILY_MERGED,
  REASON_CODES.AGGREGATION_TIMEOUT,
  REASON_CODES.CONFIDENCE_BLOCKED,
  REASON_CODES.IMAGE_REQUIRED_UNAVAILABLE,
  REASON_CODES.IDEMPOTENCY_STORE_UNAVAILABLE,
  REASON_CODES.RAW_TEXT_FALLBACK_FORBIDDEN,
  REASON_CODES.RSS_ECONOMIC_PUBLISH_FORBIDDEN,
  REASON_CODES.LOW_VALUE_SKIPPED,
  REASON_CODES.CIRCUIT_BREAKER_OPEN,
]);

const SOURCE_REASON_CODES = new Set([
  REASON_CODES.SOURCE_NOT_ALLOWED,
  REASON_CODES.SOURCE_COPY_SIMILARITY_TOO_HIGH,
  REASON_CODES.RSS_EDITORIAL_BLOCKED,
  REASON_CODES.FACT_INTEGRITY_FAILED,
  REASON_CODES.PARSER_CONFIDENCE_LOW,
]);

function classifyBlockReason(reasonCode, stage = null) {
  if (!reasonCode) return FAILURE_ATTRIBUTION.PIPELINE_CAUSED;
  if (PIPELINE_REASON_CODES.has(reasonCode)) return FAILURE_ATTRIBUTION.PIPELINE_CAUSED;
  if (SOURCE_REASON_CODES.has(reasonCode)) return FAILURE_ATTRIBUTION.SOURCE_CAUSED;
  if (stage === "source_policy") return FAILURE_ATTRIBUTION.SOURCE_CAUSED;
  if (stage === "copy_similarity") return FAILURE_ATTRIBUTION.SOURCE_CAUSED;
  if (stage === "fact_integrity") return FAILURE_ATTRIBUTION.SOURCE_CAUSED;
  if (reasonCode === REASON_CODES.RSS_FETCH_FAILED) return FAILURE_ATTRIBUTION.NETWORK_CAUSED;
  if (reasonCode === REASON_CODES.DELIVERY_FAILED) return FAILURE_ATTRIBUTION.NETWORK_CAUSED;
  return FAILURE_ATTRIBUTION.PIPELINE_CAUSED;
}

function classifySampleEntry(entry = {}) {
  if (entry.attribution) return entry.attribution;
  if (entry.zeroArticleCycles && entry.fetchSuccess) return FAILURE_ATTRIBUTION.EXPECTED_NO_DATA;
  if (entry.fetchSuccess) return FAILURE_ATTRIBUTION.EXPECTED_NO_DATA;
  if (entry.fetchFailure) return FAILURE_ATTRIBUTION.NETWORK_CAUSED;
  if (entry.invalidStructure || entry.promotionalLeakAttempts) return FAILURE_ATTRIBUTION.SOURCE_CAUSED;
  if (entry.parseFailure) return FAILURE_ATTRIBUTION.SOURCE_CAUSED;
  if (entry.duplicateBlocks || entry.copyBlocks) return FAILURE_ATTRIBUTION.PIPELINE_CAUSED;
  if (entry.parseSuccess) return FAILURE_ATTRIBUTION.EXPECTED_NO_DATA;
  return FAILURE_ATTRIBUTION.EXPECTED_NO_DATA;
}

module.exports = {
  FAILURE_ATTRIBUTION,
  classifyBlockReason,
  classifySampleEntry,
};
