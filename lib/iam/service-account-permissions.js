/**
 * Minimum IAM permissions per service account (machine identity).
 */
import { IAM_PERMISSIONS, IAM_SERVICE_ACCOUNTS } from "./constants.js";

/** Cron identity — route-backed minimum for protected cron web routes only. */
export const CRON_SERVICE_PERMISSIONS = Object.freeze([IAM_PERMISSIONS.SYSTEM_CRON_READ]);

export const SERVICE_ACCOUNT_PERMISSION_MATRIX = Object.freeze({
  [IAM_SERVICE_ACCOUNTS.CRON]: CRON_SERVICE_PERMISSIONS,
  [IAM_SERVICE_ACCOUNTS.NEWS_WORKER]: Object.freeze([
    IAM_PERMISSIONS.NEWS_PUBLISH,
    IAM_PERMISSIONS.NEWS_MANAGE,
  ]),
  [IAM_SERVICE_ACCOUNTS.PRICE_ALERT_WORKER]: Object.freeze([
    IAM_PERMISSIONS.SYSTEM_CRON_READ,
    IAM_PERMISSIONS.DASHBOARD_MUTATIONS,
    IAM_PERMISSIONS.SYSTEM_NOTIFICATIONS_TEST,
  ]),
  [IAM_SERVICE_ACCOUNTS.INSTANT_ANALYSIS_WORKER]: Object.freeze([
    IAM_PERMISSIONS.ANALYSIS_MANAGE,
    IAM_PERMISSIONS.ANALYSIS_PUBLISH,
  ]),
  [IAM_SERVICE_ACCOUNTS.TELEGRAM_BOT]: Object.freeze([
    IAM_PERMISSIONS.NEWS_PUBLISH,
    IAM_PERMISSIONS.SUPPORT_MANAGE,
  ]),
  [IAM_SERVICE_ACCOUNTS.SUBSCRIPTION_MAINTENANCE_WORKER]: Object.freeze([
    IAM_PERMISSIONS.SYSTEM_CRON_READ,
    IAM_PERMISSIONS.SUBSCRIPTIONS_READ,
    IAM_PERMISSIONS.SUBSCRIPTIONS_MANAGE,
  ]),
});

export function permissionsForServiceAccount(accountId) {
  return SERVICE_ACCOUNT_PERMISSION_MATRIX[accountId] || [];
}
